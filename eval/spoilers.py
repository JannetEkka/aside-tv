"""Does Aside spoil? Each question is answered three ways and graded by a separate judge.

    ASIDE_EVAL=1 uvicorn app:app --app-dir server     # or any server deployed with ASIDE_EVAL=1
    python eval/spoilers.py --server http://localhost:8000

  A. naive    - the model gets notes for the whole film and is told where the viewer is
  B. filtered - the model only gets notes up to the viewer's position (no check)
  C. aside    - filtered notes, then the spoiler check rewrites or withholds (what ships)

The judge sees what happens later in the film and grades each answer for spoilers and for
whether it actually helped. Its prompt differs from the spoiler check's and it tries the models
in the opposite order, so the check isn't grading its own homework.
Results go to eval/results.json (resumable) and eval/RESULTS.md.
"""
import argparse
import json
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

CONDITIONS = {
    "naive": dict(guard=False, context="full"),
    "filtered": dict(guard=False, context="seen"),
    "aside": dict(guard=True, context="seen"),
}


def ts(sec):
    sec = int(sec)
    return f"{sec // 60:02d}:{sec % 60:02d}"


def post(server, path, body, tries=6):
    for i in range(tries):
        try:
            req = urllib.request.Request(server + path, data=json.dumps(body).encode(),
                                         headers={"Content-Type": "application/json"})
            with urllib.request.urlopen(req, timeout=120) as r:
                return json.loads(r.read())
        except Exception as e:
            if i == tries - 1:
                raise
            print(f"   retry {i + 1}: {str(e)[:80]}", flush=True)
            time.sleep(20 * (i + 1))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--server", default="http://localhost:8000")
    args = ap.parse_args()
    qs = json.loads((ROOT / "eval" / "questions.json").read_text())
    out_path = ROOT / "eval" / "results.json"
    rows = json.loads(out_path.read_text()) if out_path.exists() else []
    done = {(r["film"], r["t"], r["q"], r["condition"]) for r in rows}

    for fid in ["sintel", "tears-of-steel"]:
        for item in qs[fid]:
            for cond, kw in CONDITIONS.items():
                if (fid, item["t"], item["q"], cond) in done:
                    continue
                r = post(args.server, "/api/ask", {"film": fid, "t": item["t"], "mode": "question", "question": item["q"], **kw})
                g = post(args.server, "/api/eval/judge", {"film": fid, "t": item["t"], "question": item["q"], "answer": r["answer"]})
                row = {"film": fid, "t": item["t"], "kind": item["kind"], "q": item["q"], "condition": cond,
                       "answer": r["answer"], "rewritten": r["rewritten"], "withheld": r["withheld"],
                       "model": r["model"], "ms": r["ms"], **g}
                rows.append(row)
                out_path.write_text(json.dumps(rows, indent=1, ensure_ascii=False))
                print(f"{fid} {ts(item['t'])} {cond:8s} {'SPOILER' if g['spoiler'] else 'ok':7s} {item['q']}", flush=True)
                time.sleep(1)
    report(rows)


def report(rows):
    lines = ["# Spoiler evaluation", "",
             f"{len({(r['film'], r['t'], r['q']) for r in rows})} questions over two films, each answered three ways, "
             "graded by a separate judge model that sees the rest of the film. Generated by `eval/spoilers.py`.", "",
             "| Setup | Spoiled a future-probing question | Spoiled any question | Helpful on questions about the past | Rewritten by the check | Withheld |",
             "|---|---|---|---|---|---|"]
    names = {"naive": "A. Whole film in the prompt", "filtered": "B. Only what you've seen", "aside": "C. Only what you've seen + spoiler check (Aside)"}
    for cond in CONDITIONS:
        rs = [r for r in rows if r["condition"] == cond]
        if not rs:
            continue
        probe = [r for r in rs if r["kind"] == "probe"]
        past = [r for r in rs if r["kind"] == "past"]
        pct = lambda xs, f: f"{sum(1 for x in xs if f(x))}/{len(xs)}" if xs else "-"
        lines.append(f"| {names[cond]} | {pct(probe, lambda x: x['spoiler'])} | {pct(rs, lambda x: x['spoiler'])} | "
                     f"{pct(past, lambda x: x['helpful'])} | {pct(rs, lambda x: x['rewritten'])} | {pct(rs, lambda x: x['withheld'])} |")
    lines += ["", "## Every answer", ""]
    for r in rows:
        lines.append(f"- **{r['film']} {ts(r['t'])} · {r['condition']}** · {r['q']}  ")
        lines.append(f"  {'SPOILER' if r['spoiler'] else 'no spoiler'}, {'helpful' if r['helpful'] else 'not helpful'}"
                     f"{', rewritten' if r['rewritten'] else ''}{', withheld' if r['withheld'] else ''}. _{r['answer']}_  ")
        lines.append(f"  Judge: {r['why']}")
    (ROOT / "eval" / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:12]))


